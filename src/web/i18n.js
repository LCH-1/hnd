const KO_BY_EN = new Map(Object.entries(EN).map(([ko, en]) => [en, ko]));
const browserStorage = globalThis.localStorage;
let preference = normalizePreference(browserStorage?.getItem?.(STORAGE_KEY)) || "auto";
let language = resolveLanguage(preference);
let observer = null;

export function normalizePreference(value) {
  const source = String(value ?? "").trim().toLowerCase();
  if (source === "auto") return "auto";
  if (["ko", "kr", "ko-kr", "korean"].includes(source)) return "ko";
  if (["en", "en-us", "en-gb", "english"].includes(source)) return "en";
  return null;
}

function browserLanguage() {
  const browserNavigator = globalThis.navigator;
  const values = Array.isArray(browserNavigator?.languages) && browserNavigator.languages.length
    ? browserNavigator.languages
    : [browserNavigator?.language];
  return values.some((value) => /^ko(?:-|$)/i.test(String(value ?? ""))) ? "ko" : "en";
}

function resolveLanguage(value) {
  return value === "auto" ? browserLanguage() : value;
}

export function currentLanguage() {
  return language;
}

export function currentLocale() {
  return language === "ko" ? "ko-KR" : "en-US";
}

export function languagePreference() {
  return preference;
}

export function t(value) {
  const source = String(value ?? "");
  const key = source.replace(/\s+/gu, " ").trim();
  if (language === "ko") return KO_BY_EN.get(key) ?? source;
  return EN[key] ?? source;
}

function translateTextNode(node) {
  const source = node.nodeValue || "";
  const trimmed = source.trim();
  if (!trimmed) return;
  const translated = t(trimmed);
  if (translated === trimmed) return;
  node.nodeValue = source.replace(trimmed, translated);
}

function translateElement(root) {
  if (!(root instanceof Element)) return;
  const elements = [root, ...root.querySelectorAll("[aria-label], [placeholder], [title]")];
  for (const element of elements) {
    for (const attribute of ["aria-label", "placeholder", "title"]) {
      if (element.hasAttribute(attribute)) {
        element.setAttribute(attribute, t(element.getAttribute(attribute)));
      }
    }
  }
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) translateTextNode(node);
}

export function translateDocument() {
  if (!globalThis.document?.documentElement || !document.body) return;
  document.documentElement.lang = language;
  document.title = t(document.title);
  translateElement(document.body);
}

export function setLanguagePreference(value, { persist = true } = {}) {
  const normalized = normalizePreference(value);
  if (!normalized) throw new TypeError("Language must be auto, ko, or en.");
  preference = normalized;
  language = resolveLanguage(preference);
  if (persist) browserStorage?.setItem?.(STORAGE_KEY, preference);
  translateDocument();
  globalThis.window?.dispatchEvent?.(new CustomEvent("hnd:language", { detail: { preference, language } }));
  return { preference, language };
}

export function applyAccountLanguage(value) {
  return setLanguagePreference(normalizePreference(value) || "auto");
}

export function startI18n() {
  if (!globalThis.document?.body || typeof MutationObserver !== "function") return;
  translateDocument();
  if (observer) return;
  observer = new MutationObserver((records) => {
    for (const record of records) {
      if (record.type === "characterData") translateTextNode(record.target);
      for (const node of record.addedNodes) {
        if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
        else translateElement(node);
      }
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
}
